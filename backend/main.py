# ── 辅助函数 ───────────────────────────────────────────────────────

async def call_deepseek(system: str, user: str, temperature: float = 0.85) -> str:
    """调用 DeepSeek API"""
    if not DEEPSEEK_API_KEY:
        raise HTTPException(status_code=500, detail="DEEPSEEK_API_KEY 未配置")

    async with httpx.AsyncClient(timeout=90.0) as client:
        resp = await client.post(
            f"{DEEPSEEK_BASE_URL}/v1/chat/completions",
            headers={
                "Authorization": f"Bearer {DEEPSEEK_API_KEY}",
                "Content-Type": "application/json",
            },
            json={
                "model": DEEPSEEK_MODEL,
                "messages": [
                    {"role": "system", "content": system},
                    {"role": "user", "content": user},
                ],
                "temperature": temperature,
                "max_tokens": 1200,
            },
        )
        if resp.status_code != 200:
            raise HTTPException(status_code=502, detail=f"DeepSeek API 错误: {resp.text}")
        data = resp.json()
        return data["choices"][0]["message"]["content"]


def build_style_note(style: str) -> str:
    return STYLE_PROMPTS.get(style, STYLE_PROMPTS["温柔派"])


