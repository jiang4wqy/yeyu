def parse_json_response(text: str) -> dict:
    """尝试从 AI 回复中提取 JSON"""
    try:
        # 尝试直接解析
        return json.loads(text)
    except json.JSONDecodeError:
        # 尝试取 ```json ... ``` 代码块
        if "```json" in text:
            start = text.index("```json") + 7
            end = text.index("```", start)
            return json.loads(text[start:end].strip())
        if "{" in text and "}" in text:
            start = text.index("{")
            end = text.rindex("}") + 1
            return json.loads(text[start:end].strip())
        # 兜底：把整段文字当 main_content
        return {
            "title": "夜语",
            "main_content": text,
            "keywords": [],
            "mood_color": "#5B6E8C",
            "share_quote": text[:20] if len(text) > 20 else text,
        }


